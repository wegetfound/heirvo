//! Demo content for the library — mirrors `src/screens/library/data/mockDiscs.ts`
//! so the UI is interactive on first launch. Idempotent: a no-op if any disc
//! already exists.

use crate::error::AppResult;
use crate::library::queries;
use crate::library::types::{ts_to_sec, Disc, Person, Scene, TopicTag, TranscriptLine};
use crate::session::db::Db;

fn l(time: &str, speaker: &str, text: &str) -> TranscriptLine {
    TranscriptLine {
        time: time.into(),
        time_sec: ts_to_sec(time),
        speaker: Some(speaker.into()),
        text: text.into(),
        is_stage_direction: None,
    }
}

fn sd(time: &str, text: &str) -> TranscriptLine {
    TranscriptLine {
        time: time.into(),
        time_sec: ts_to_sec(time),
        speaker: None,
        text: text.into(),
        is_stage_direction: Some(true),
    }
}

fn s(time: &str, title: &str, desc: Option<&str>) -> Scene {
    Scene {
        time: time.into(),
        time_sec: ts_to_sec(time),
        title: title.into(),
        description: desc.map(str::to_string),
    }
}

fn t(label: &str, count: i64) -> TopicTag {
    TopicTag {
        label: label.into(),
        count,
    }
}

fn p(initials: &str, name: &str) -> Person {
    Person {
        initials: initials.into(),
        name: name.into(),
    }
}

/// Seed the 12 demo discs. Returns the number of discs inserted (0 if the
/// library is already populated).
pub async fn seed_demo_data(db: &Db) -> AppResult<u32> {
    let existing = queries::count_discs(db).await?;
    if existing > 0 {
        return Ok(0);
    }

    let discs = build_demo_discs();
    let mut inserted = 0u32;
    for disc in &discs {
        queries::insert_disc(db, disc).await?;
        inserted += 1;
    }
    Ok(inserted)
}

