import type { Disc, TranscriptLine, Scene } from "./types";

/** "HH:MM:SS" → seconds. Accepts "MM:SS" too. */
export function tsToSec(t: string): number {
  const parts = t.split(":").map((n) => parseInt(n, 10));
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  return 0;
}

function L(time: string, speaker: string, text: string): TranscriptLine {
  return { time, timeSec: tsToSec(time), speaker, text };
}
function SD(time: string, text: string): TranscriptLine {
  return { time, timeSec: tsToSec(time), text, isStageDirection: true };
}
function S(time: string, title: string, description?: string): Scene {
  return { time, timeSec: tsToSec(time), title, description };
}

